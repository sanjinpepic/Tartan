#!/usr/bin/env python3
"""
Build web/lib/musclemap-paths.ts, the outlines of the 2D muscle map (web/lib/muscles.ts), from
MuscleMap by Melih Colpan (MIT, https://github.com/melihcolpan/MuscleMap; see NOTICE.md), which
keeps its SVG path data in Swift source. Four views (man and woman, front and back), each a
viewBox and, per body part, its paths for the left and right side and any on the midline.
MuscleMap's finer sub-groups (upper chest, outer quad, front deltoid…) overlap the whole muscles
and are left out; the parts are renamed onto Tartan's muscles where they match one, and kept under
their own names otherwise (drawn as the quiet body).

  python3 scripts/build-musclemap.py <MuscleMap checkout>
"""
import json
import os
import re
import sys

SRC = os.path.join(sys.argv[1], "Sources", "MuscleMap", "Data")
OUT = os.path.join(os.path.dirname(__file__), "..", "web", "lib", "musclemap-paths.ts")

SUB = {"upperChest", "lowerChest", "innerQuad", "outerQuad", "upperAbs", "lowerAbs", "frontDeltoid", "rearDeltoid", "upperTrapezius", "lowerTrapezius"}
RENAME = {
    "trapezius": "traps", "deltoids": "delts", "chest": "chest", "biceps": "biceps", "triceps": "triceps",
    "forearm": "forearms", "upperBack": "lats", "rhomboids": "upper_back", "lowerBack": "lower_back", "abs": "abs",
    "obliques": "obliques", "hipFlexors": "hip_flexors", "gluteal": "glutes", "adductors": "adductors",
    "quadriceps": "quads", "hamstring": "hamstrings", "calves": "calves", "tibialis": "tibialis",
    "rotatorCuff": "upper_back", "serratus": "serratus",
}
VIEWS = {("m", "front"): "MaleFrontPaths.swift", ("m", "back"): "MaleBackPaths.swift", ("f", "front"): "FemaleFrontPaths.swift", ("f", "back"): "FemaleBackPaths.swift"}

vb_src = open(os.path.join(SRC, "BodyPathData.swift")).read()
def viewbox(name):
    m = re.search(name + r" = BodyViewBox\(\s*origin: CGPoint\(x: ([\d.]+), y: ([\d.]+)\),\s*size: CGSize\(width: ([\d.]+), height: ([\d.]+)\)", vb_src)
    return " ".join(m.groups())

out = {}
for (sex, side), fn in VIEWS.items():
    src = open(os.path.join(SRC, fn)).read()
    parts = {}
    for block in re.finditer(r"BodyPartPathData\(\s*slug: \.(\w+),(.*?)\n        \)", src, re.S):
        slug, body = block.group(1), block.group(2)
        if slug in SUB:
            continue
        name = RENAME.get(slug, slug)
        entry = parts.setdefault(name, {})
        for key, short in (("common", "c"), ("left", "l"), ("right", "r")):
            m = re.search(key + r": \[(.*?)\]", body, re.S)
            if m:
                paths = re.findall(r'"([^"]+)"', m.group(1))
                if paths:
                    entry.setdefault(short, []).extend(paths)
    out.setdefault(sex, {})[side] = {"vb": viewbox(("male" if sex == "m" else "female") + side.capitalize()), "parts": parts}

body = json.dumps(out, separators=(",", ":"))
with open(OUT, "w") as f:
    f.write("// Generated by scripts/build-musclemap.py from MuscleMap by Melih Colpan (MIT; see NOTICE.md). Do not edit.\n")
    f.write("// Each view: a viewBox and, per part, its paths: l (the body's left), r (right), c (midline).\n")
    f.write("type Paths = { l?: string[]; r?: string[]; c?: string[] };\n")
    f.write("export type View = { vb: string; parts: Record<string, Paths> };\n")
    f.write("const PATHS: Record<\"m\" | \"f\", Record<\"front\" | \"back\", View>> = " + body + ";\nexport default PATHS;\n")
print(OUT, os.path.getsize(OUT) // 1024, "KB;", {f"{s}-{v}": sorted(out[s][v]["parts"]) for s in out for v in out[s]})
